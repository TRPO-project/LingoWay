-- LingoWay shared database v0.2; PostgreSQL 16. Bootstrap for an EMPTY database.
-- This is not a migration: the old be3.* prototype is not dropped or modified.
-- Normal application startup uses internal/database + GORM models. Do not run
-- this bootstrap over existing GORM tables; use reviewed migrations for data changes.
BEGIN;

CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL CHECK (length(btrim(email)) BETWEEN 3 AND 320),
    password_hash text NOT NULL CHECK (length(btrim(password_hash)) > 0),
    name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100),
    role text NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'teacher', 'admin')),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_unique ON public.users (lower(btrim(email)));

CREATE TABLE public.topics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100)
);

CREATE TABLE public.materials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id bigint NOT NULL REFERENCES public.users(id),
    request_key uuid NOT NULL DEFAULT gen_random_uuid(),
    topic_id bigint REFERENCES public.topics(id),
    title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    kind text NOT NULL CHECK (kind IN ('text', 'file', 'url', 'audio')),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'ready', 'failed')),
    source_text text,
    source_url text,
    object_key text, -- Private S3 key; bucket is configured via S3_BUCKET.
    original_filename text,
    content_type text,
    size_bytes bigint CHECK (size_bytes > 0),
    content_sha256 text CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
    extracted_text text,
    level text CHECK (level IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
    error_code text,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, owner_user_id),
    UNIQUE (owner_user_id, request_key),
    CHECK (
        (kind = 'text' AND source_text IS NOT NULL AND length(btrim(source_text)) > 0
            AND source_url IS NULL AND object_key IS NULL) OR
        (kind = 'url' AND source_url IS NOT NULL AND length(btrim(source_url)) > 0
            AND source_text IS NULL AND object_key IS NULL) OR
        (kind IN ('file', 'audio') AND object_key IS NOT NULL AND length(btrim(object_key)) > 0
            AND source_text IS NULL AND source_url IS NULL
            AND content_type IS NOT NULL AND size_bytes IS NOT NULL AND content_sha256 IS NOT NULL)),
    CHECK (status <> 'ready' OR (extracted_text IS NOT NULL
        AND length(btrim(extracted_text)) BETWEEN 1 AND 200000 AND level IS NOT NULL)),
    CHECK ((status = 'failed') = (error_code IS NOT NULL))
);
CREATE INDEX materials_owner_idx ON public.materials(owner_user_id, created_at DESC);

CREATE TABLE public.modules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Internal ownership, never exposed in a public module DTO. System modules
    -- may have no creator; private modules must retain their access owner.
    created_by_user_id bigint REFERENCES public.users(id),
    material_id bigint,
    topic_id bigint NOT NULL REFERENCES public.topics(id),
    title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    difficulty text NOT NULL CHECK (difficulty IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
    visibility text NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'public')),
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'generating', 'ready', 'failed')),
    created_at timestamptz NOT NULL DEFAULT now(),
    published_at timestamptz,
    UNIQUE (id, created_by_user_id),
    FOREIGN KEY (material_id, created_by_user_id)
        REFERENCES public.materials(id, owner_user_id) ON DELETE CASCADE,
    CONSTRAINT modules_private_creator_check
        CHECK (visibility <> 'private' OR created_by_user_id IS NOT NULL),
    CONSTRAINT modules_material_owner_check
        CHECK (material_id IS NULL OR created_by_user_id IS NOT NULL),
    CONSTRAINT modules_material_visibility_check
        CHECK (material_id IS NULL OR visibility = 'private'),
    CHECK ((status = 'ready') = (published_at IS NOT NULL))
);
CREATE INDEX modules_catalog_idx ON public.modules(topic_id, difficulty) WHERE status = 'ready';
CREATE INDEX modules_creator_idx ON public.modules(created_by_user_id, created_at DESC);
CREATE INDEX modules_material_idx ON public.modules(material_id) WHERE material_id IS NOT NULL;

CREATE TABLE public.exercises (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id bigint NOT NULL REFERENCES public.modules(id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position > 0),
    type text NOT NULL CHECK (type IN (
        'vocabulary_gap', 'vocabulary_matching_translation', 'vocabulary_matching_definition',
        'vocabulary_context_choice', 'grammar_brackets', 'grammar_tense',
        'grammar_word_order', 'comprehension_question', 'reasoning_question')),
    instruction text NOT NULL CHECK (length(btrim(instruction)) > 0),
    question_text text NOT NULL CHECK (length(btrim(question_text)) > 0),
    content jsonb NOT NULL CHECK (jsonb_typeof(content) = 'object'), -- PUBLIC.
    answer_key jsonb NOT NULL CHECK (jsonb_typeof(answer_key) = 'object'), -- PRIVATE.
    explanation text NOT NULL DEFAULT '', -- PRIVATE until the answer is checked.
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (module_id, position)
    -- level and topic are inherited from modules, not duplicated here.
);

CREATE TABLE public.answers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id),
    exercise_id bigint NOT NULL REFERENCES public.exercises(id) ON DELETE CASCADE,
    request_key uuid NOT NULL DEFAULT gen_random_uuid(),
    response jsonb NOT NULL CHECK (jsonb_typeof(response) = 'object'),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'checked', 'failed')),
    score numeric(6,5) CHECK (score >= 0 AND score <= 1),
    is_correct boolean GENERATED ALWAYS AS (score = 1) STORED,
    feedback text,
    error_code text,
    created_at timestamptz NOT NULL DEFAULT now(),
    checked_at timestamptz,
    UNIQUE (id, user_id),
    UNIQUE (user_id, request_key),
    CHECK ((status = 'checked' AND score IS NOT NULL AND feedback IS NOT NULL AND checked_at IS NOT NULL)
        OR (status <> 'checked' AND score IS NULL AND feedback IS NULL AND checked_at IS NULL)),
    CHECK ((status = 'failed') = (error_code IS NOT NULL))
);
CREATE INDEX answers_user_exercise_idx ON public.answers(user_id, exercise_id, created_at DESC);

-- ONE LLM table: request, result and small durable work queue.
-- Prompt text/schema live in versioned application files; no DB cache in v0.2.
CREATE TABLE public.llm_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id bigint NOT NULL REFERENCES public.users(id),
    request_key uuid NOT NULL DEFAULT gen_random_uuid(),
    operation text NOT NULL CHECK (operation IN ('prepare_material', 'generate_module', 'check_answer')),
    material_id bigint,
    module_id bigint,
    answer_id bigint,
    status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'succeeded', 'failed')),
    parameters jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(parameters) = 'object'),
    prompt_version text NOT NULL CHECK (length(btrim(prompt_version)) > 0),
    provider text,
    model text,
    result jsonb CHECK (jsonb_typeof(result) = 'object'), -- IDs/summary, not raw private content.
    error_code text,
    error_message text,
    attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    available_at timestamptz NOT NULL DEFAULT now(),
    lease_token uuid,
    lease_expires_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    UNIQUE (owner_user_id, operation, request_key),
    FOREIGN KEY (material_id, owner_user_id) REFERENCES public.materials(id, owner_user_id) ON DELETE CASCADE,
    FOREIGN KEY (module_id, owner_user_id) REFERENCES public.modules(id, created_by_user_id) ON DELETE CASCADE,
    FOREIGN KEY (answer_id, owner_user_id) REFERENCES public.answers(id, user_id) ON DELETE CASCADE,
    CHECK (
        (operation = 'prepare_material' AND material_id IS NOT NULL AND module_id IS NULL AND answer_id IS NULL) OR
        (operation = 'generate_module' AND material_id IS NULL AND module_id IS NOT NULL AND answer_id IS NULL) OR
        (operation = 'check_answer' AND material_id IS NULL AND module_id IS NULL AND answer_id IS NOT NULL)),
    CHECK ((status = 'running' AND lease_token IS NOT NULL AND lease_expires_at IS NOT NULL AND attempt_count > 0)
        OR (status <> 'running' AND lease_token IS NULL AND lease_expires_at IS NULL)),
    CHECK ((status IN ('succeeded', 'failed')) = (finished_at IS NOT NULL)),
    CHECK ((status = 'failed') = (error_code IS NOT NULL)),
    CHECK (status <> 'succeeded' OR result IS NOT NULL)
);
CREATE UNIQUE INDEX llm_material_active_unique ON public.llm_requests(material_id)
    WHERE material_id IS NOT NULL AND status IN ('queued', 'running');
CREATE UNIQUE INDEX llm_module_active_unique ON public.llm_requests(module_id)
    WHERE module_id IS NOT NULL AND status IN ('queued', 'running');
CREATE UNIQUE INDEX llm_answer_active_unique ON public.llm_requests(answer_id)
    WHERE answer_id IS NOT NULL AND status IN ('queued', 'running');
CREATE INDEX llm_queue_idx ON public.llm_requests(available_at, created_at) WHERE status = 'queued';
CREATE INDEX llm_expired_lease_idx ON public.llm_requests(lease_expires_at) WHERE status = 'running';
CREATE INDEX llm_owner_idx ON public.llm_requests(owner_user_id, created_at DESC);

CREATE TABLE public.catalog_materials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id bigint NOT NULL REFERENCES public.topics(id),
    level text NOT NULL CHECK (level IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
    type text NOT NULL CHECK (type IN ('text', 'link')),
    title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    description text CHECK (description IS NULL OR length(description) <= 500),
    body text,
    url text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (
        (type = 'text' AND body IS NOT NULL AND length(btrim(body)) > 0
            AND length(body) <= 100000 AND url IS NULL) OR
        (type = 'link' AND url IS NOT NULL AND length(url) <= 2048
            AND url ~ '^https?://[^[:space:]]+$' AND body IS NULL))
);
CREATE INDEX catalog_materials_topic_level_idx ON public.catalog_materials(topic_id, level, id DESC);

CREATE TABLE public.catalog_material_favorites (
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    material_id bigint NOT NULL REFERENCES public.catalog_materials(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, material_id)
);
CREATE INDEX catalog_favorites_material_idx ON public.catalog_material_favorites(material_id);

CREATE FUNCTION public.guard_exercise_write() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE module_status text;
BEGIN
    IF TG_OP = 'DELETE' THEN
        SELECT status INTO module_status FROM public.modules WHERE id = OLD.module_id FOR UPDATE;
        IF FOUND AND module_status = 'ready' THEN
            RAISE EXCEPTION 'delete the whole published module, not one exercise';
        END IF;
        RETURN OLD; -- During whole-module cascade the parent is already removed.
    END IF;
    IF TG_OP = 'UPDATE' AND (NEW.id <> OLD.id OR NEW.module_id <> OLD.module_id) THEN
        RAISE EXCEPTION 'exercise identity and module are immutable';
    END IF;
    SELECT status INTO module_status FROM public.modules WHERE id = NEW.module_id FOR UPDATE;
    IF NOT FOUND OR module_status = 'ready' THEN
        RAISE EXCEPTION 'exercise requires an unpublished module';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER exercises_write_guard BEFORE INSERT OR UPDATE OR DELETE ON public.exercises
    FOR EACH ROW EXECUTE FUNCTION public.guard_exercise_write();

CREATE FUNCTION public.guard_module_write() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE exercise_count integer; creator_role text;
BEGIN
    IF TG_OP = 'INSERT' AND NEW.status = 'ready' THEN
        RAISE EXCEPTION 'create a draft module before publication';
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF NEW.id <> OLD.id OR NEW.created_by_user_id IS DISTINCT FROM OLD.created_by_user_id
            OR NEW.material_id IS DISTINCT FROM OLD.material_id THEN
            RAISE EXCEPTION 'module identity and source are immutable';
        END IF;
        IF OLD.status = 'ready' AND NEW IS DISTINCT FROM OLD THEN
            RAISE EXCEPTION 'published module is immutable; create a copy';
        END IF;
    END IF;
    -- A NULL creator denotes an internally managed system/catalog module.
    -- Authorization for managing such modules is enforced by the admin service.
    IF NEW.visibility = 'public' AND NEW.created_by_user_id IS NOT NULL THEN
        SELECT role INTO creator_role FROM public.users WHERE id = NEW.created_by_user_id;
        IF creator_role IS NULL OR creator_role NOT IN ('teacher', 'admin') THEN
            RAISE EXCEPTION 'only a teacher or admin can create a public module';
        END IF;
    END IF;
    IF NEW.status = 'ready' THEN
        SELECT count(*) INTO exercise_count FROM public.exercises WHERE module_id = NEW.id;
        IF exercise_count < 2 THEN RAISE EXCEPTION 'module requires at least two exercises'; END IF;
        IF EXISTS (SELECT 1 FROM public.exercises WHERE module_id = NEW.id
            AND (answer_key = '{}'::jsonb OR length(btrim(explanation)) = 0)) THEN
            RAISE EXCEPTION 'published exercises require answer keys and explanations';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER modules_write_guard BEFORE INSERT OR UPDATE ON public.modules
    FOR EACH ROW EXECUTE FUNCTION public.guard_module_write();

CREATE FUNCTION public.guard_answer_write() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE module_status text; module_owner bigint; module_visibility text;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.id <> OLD.id OR NEW.user_id <> OLD.user_id OR NEW.exercise_id <> OLD.exercise_id
            OR NEW.response IS DISTINCT FROM OLD.response OR NEW.request_key <> OLD.request_key THEN
            RAISE EXCEPTION 'submitted response is immutable; submit a new answer';
        END IF;
        IF OLD.status = 'checked' AND NEW IS DISTINCT FROM OLD THEN
            RAISE EXCEPTION 'checked answer is immutable';
        END IF;
        RETURN NEW;
    END IF;
    SELECT m.status, m.created_by_user_id, m.visibility
        INTO module_status, module_owner, module_visibility
        FROM public.exercises e JOIN public.modules m ON m.id = e.module_id
        WHERE e.id = NEW.exercise_id FOR SHARE OF m;
    IF NOT FOUND OR module_status <> 'ready' THEN RAISE EXCEPTION 'answer requires a ready module'; END IF;
    IF module_visibility = 'private' AND module_owner IS DISTINCT FROM NEW.user_id THEN
        RAISE EXCEPTION 'private module belongs to another user';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER answers_write_guard BEFORE INSERT OR UPDATE ON public.answers
    FOR EACH ROW EXECUTE FUNCTION public.guard_answer_write();

-- Application/worker rules (these are not SQL JSON-schema validation):
-- * Derive users/owners from JWT. Public DTOs must omit password_hash, answer_key,
--   modules.created_by_user_id, explanation before checking, and raw LLM parameters/results.
-- * System modules have no creator and are managed only by the admin service.
--   Generated/private modules require an owner; a source material must belong
--   to that owner and can never be made public by removing the creator.
-- * Validate content/answer_key with exercise-templates.json before publication:
--   single choice = 4 options/one correct ID; matching = 4..6 shuffled entries
--   and bijective key; word order = ordered subset may omit distractor tokens.
-- * Publish exercises and LLM success in ONE transaction after validating count,
--   type distribution and EXP criteria. Never serve draft/generating exercises.
-- * Lock module on publication, answer creation and whole-module deletion.
--   One published exercise cannot be deleted; delete the whole module instead.
-- * Queue claim uses FOR UPDATE SKIP LOCKED; result commit requires the current
--   unexpired lease_token. Retry expired/transient work with bounded backoff.
-- * Idempotency uses UUIDs, no expiry: material(owner,key), answer(user,key),
--   LLM(owner,operation,key). Compare immutable original input on replay.
--   Reserve generated module+LLM request in one transaction; replay first.
-- * Whole-material/module DELETE intentionally cascades raw answers/requests.
--   Capture object keys before deletion and compensate failed S3 cleanup.
-- * No progress, personal dictionary, attempts, outbox or LLM cache in v0.2.
COMMIT;
